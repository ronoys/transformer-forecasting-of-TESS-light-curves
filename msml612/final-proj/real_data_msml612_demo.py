"""### Cell 5: Training loop (AdamW, early stopping, grad clip)
**Training loop.** AdamW, gradient clipping, early stopping on val loss, best-checkpoint restore. `use_huber` flag in config if flux outliers dominate.
"""

def train(model, train_dl, val_dl, cfg, max_epochs=None, verbose=True, history=None):
    """Returns the best-val model. Pass `history` (a dict) to collect per-epoch
    train/val loss for evaluate.py's training-curve figure."""
    model.to(DEVICE)
    if not any(p.requires_grad for p in model.parameters()):
        return model  # persistence: nothing to train
    opt = torch.optim.AdamW(model.parameters(), lr=cfg.lr)
    loss_fn = nn.HuberLoss() if cfg.use_huber else nn.MSELoss()
    best_val, best_state, bad = float("inf"), None, 0
    for epoch in range(max_epochs or cfg.max_epochs):
        model.train()
        epoch_losses = []
        for xb, yb in train_dl:
            xb, yb = xb.to(DEVICE), yb.to(DEVICE)
            opt.zero_grad()
            loss = loss_fn(model(xb), yb)
            loss.backward()
            nn.utils.clip_grad_norm_(model.parameters(), 1.0)
            opt.step()
            epoch_losses.append(loss.item())
        model.eval()
        with torch.no_grad():
            vl = np.mean([loss_fn(model(x.to(DEVICE)), t.to(DEVICE)).item() for x, t in val_dl])
        if history is not None:
            history.setdefault("train", []).append(float(np.mean(epoch_losses)))
            history.setdefault("val", []).append(float(vl))
        if verbose: print(f"  epoch {epoch:02d} val_loss={vl:.3e}")
        if vl < best_val - 1e-9:
            best_val, best_state, bad = vl, {k: v.clone() for k, v in model.state_dict().items()}, 0
        else:
            bad += 1
            if bad >= cfg.patience: break
    model.load_state_dict(best_state)
    return model

"""### Cell 6: Eval harness — every model goes through this
**Eval harness.** Every model, baseline or not, goes through the identical predict/metrics/plot path, so numbers in the report are directly comparable.
"""

@torch.no_grad()
def predict(model, dl):
    model.eval().to(DEVICE)
    P, Y = [], []
    for xb, yb in dl:
        P.append(model(xb.to(DEVICE)).cpu()); Y.append(yb)
    return (from_model_units(torch.cat(P).numpy()),   # metrics reported in real flux units
            from_model_units(torch.cat(Y).numpy()))

def metrics(pred, true):
    return {"MAE": float(np.abs(pred - true).mean()),
            "RMSE": float(np.sqrt(((pred - true) ** 2).mean()))}

def plot_examples(pred, true, X, idxs, title=""):
    fig, axes = plt.subplots(1, len(idxs), figsize=(4 * len(idxs), 3), sharey=False)
    for ax, i in zip(np.atleast_1d(axes), idxs):
        L = cfg.input_len
        ax.plot(range(L), X[i], lw=0.7, color="gray", label="context")
        ax.plot(range(L, L + cfg.target_len), true[i], lw=1.5, label="true")
        ax.plot(range(L, L + cfg.target_len), pred[i], lw=1.5, ls="--", label="pred")
        ax.set_xlim(L - 80, L + cfg.target_len)
    axes.flat[0].legend(fontsize=8); fig.suptitle(title); plt.tight_layout(); fig.savefig(f"outputs/examples_{title.split(':')[0].strip().replace(' ','_')}.png", dpi=150, bbox_inches="tight"); plt.close(fig)

