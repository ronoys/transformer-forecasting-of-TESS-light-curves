def load_from_ronoy(path):
    z = np.load(path, allow_pickle=True)
    return {k: z[k] for k in ["X", "y", "tic_id", "split", "transit_depth"]}

def make_tess_windows(
    out_path="tess_windows.npz",
    tic_ids=(261136679, 307210830, 410153553, 150428135,
             231663901, 25155310, 260128333, 425997655),
    max_products=2,
    max_windows_per_star=200,
    seed=612,
):
    rng = np.random.default_rng(seed)
    X_all, y_all, tic_all, depth_all = [], [], [], []

    for idx, tic_id in enumerate(tic_ids, 1):
        print(f"[{idx}/{len(tic_ids)}] TIC {tic_id}")

        search = lk.search_lightcurve(f"TIC {tic_id}", mission="TESS")
        if len(search) == 0:
            print("  skipped: no light curve found")
            continue

        search = search[:max_products]

        try:
            lcc = search.download_all(
                quality_bitmask="default",
                flux_column="pdcsap_flux"
            )
        except Exception:
            lcc = search.download_all(quality_bitmask="default")

        if lcc is None or len(lcc) == 0:
            print("  skipped: download failed")
            continue

        # stitch()'s default corrector_func also calls .normalize() internally, which is what
        # crashes under this cluster's astropy/lightkurve version mismatch. Pass a no-op
        # corrector so stitch() does not normalize; manual median-normalize below covers it.
        lc = lcc.stitch(corrector_func=lambda x: x).remove_nans().remove_outliers(sigma=8)
        flux = np.asarray(lc.flux.value, dtype=np.float32)
        flux = flux[np.isfinite(flux)]

        med = np.nanmedian(flux)
        if np.isfinite(med) and med != 0:
            flux = flux / med

        total_len = cfg.input_len + cfg.target_len
        X_star, y_star, tic_star, depth_star = [], [], [], []

        for s in range(0, len(flux) - total_len + 1, cfg.target_len):
            X = flux[s : s + cfg.input_len]
            y = flux[s + cfg.input_len : s + total_len]

            if X.shape[0] != cfg.input_len or y.shape[0] != cfg.target_len:
                continue
            if not np.isfinite(X).all() or not np.isfinite(y).all():
                continue

            baseline = float(np.nanmedian(np.concatenate([X, y])))
            transit_depth = max(0.0, baseline - float(np.nanmin(y)))

            X_star.append(X.astype(np.float32))
            y_star.append(y.astype(np.float32))
            tic_star.append(int(tic_id))
            depth_star.append(np.float32(transit_depth))

        if len(X_star) > max_windows_per_star:
            keep = np.sort(rng.choice(len(X_star), max_windows_per_star, replace=False))
            X_star = [X_star[i] for i in keep]
            y_star = [y_star[i] for i in keep]
            tic_star = [tic_star[i] for i in keep]
            depth_star = [depth_star[i] for i in keep]

        print(f"  kept {len(X_star)} windows")

        X_all.extend(X_star)
        y_all.extend(y_star)
        tic_all.extend(tic_star)
        depth_all.extend(depth_star)

    X = np.asarray(X_all, dtype=np.float32)
    y = np.asarray(y_all, dtype=np.float32)
    tic_id = np.asarray(tic_all, dtype=np.int64)
    transit_depth = np.asarray(depth_all, dtype=np.float32)

    stars = np.unique(tic_id)
    rng.shuffle(stars)

    n_train = max(1, int(0.70 * len(stars)))
    n_val = max(1, int(0.15 * len(stars)))

    train_stars = set(stars[:n_train])
    val_stars = set(stars[n_train : n_train + n_val])

    split = np.empty(len(tic_id), dtype="<U5")
    for i, star in enumerate(tic_id):
        if star in train_stars:
            split[i] = "train"
        elif star in val_stars:
            split[i] = "val"
        else:
            split[i] = "test"

    np.savez_compressed(
        out_path,
        X=X,
        y=y,
        tic_id=tic_id,
        split=split,
        transit_depth=transit_depth,
    )

    return load_from_ronoy(out_path)

