"""### Cell 3: Sanity checks + loaders (Phase 0)
**Sanity checks + scaling.** Detrended flux sits at ~1.0 with deltas of ~1e-3, so raw MSE gradients are tiny. We train in `(flux - 1) * 1000` units and convert back for metrics. Leakage check enforces the split-by-star rule.
"""

def sanity_check(d):
    assert not np.isnan(d["X"]).any() and not np.isnan(d["y"]).any(), "NaNs present"
    for a, b in [("train", "val"), ("train", "test"), ("val", "test")]:
        overlap = set(d["tic_id"][d["split"] == a]) & set(d["tic_id"][d["split"] == b])
        assert not overlap, f"star leakage between {a}/{b}: {overlap}"
    assert d["X"].shape[1] == cfg.input_len and d["y"].shape[1] == cfg.target_len
    print("sanity checks passed:", {s: int((d["split"] == s).sum()) for s in ["train", "val", "test"]})

def to_model_units(a):   return (a - 1.0) * cfg.flux_scale   # center at 0, scale up
def from_model_units(a): return a / cfg.flux_scale + 1.0

def make_loader(d, split, shuffle=False):
    m = d["split"] == split
    ds = TensorDataset(torch.from_numpy(to_model_units(d["X"][m])),
                       torch.from_numpy(to_model_units(d["y"][m])))
    # num_workers stays 0: the whole split is already an in-memory tensor, so worker
    # processes would only add IPC cost — and they would re-import this module's
    # top-level driver. pin_memory still buys a faster host->device copy.
    return DataLoader(ds, batch_size=cfg.batch_size, shuffle=shuffle,
                      pin_memory=(DEVICE == "cuda"))

